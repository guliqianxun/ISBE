export const MESSAGES: Record<Lang, Record<Key, string>> = { zh, en };
export type MessageKey = Key;

export function translate(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  let text = MESSAGES[lang][key];
  // A function replacement: `$&` and the like in a value are text, not patterns.
  for (const [name, value] of Object.entries(vars ?? {}))
    text = text.replace(`{${name}}`, () => String(value));
  return text;
}

export function useT() {
  const { prefs } = usePrefs();
  return (key: Key, vars?: Record<string, string | number>) => translate(prefs.lang, key, vars);
}
