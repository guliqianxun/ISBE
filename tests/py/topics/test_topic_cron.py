@pytest.mark.parametrize(("pattern", "message"), CRONER)
def test_cron_validation_matches_the_croner_grammar(pattern: str, message: str | None) -> None:
    if message is None:
        check(pattern)
    else:
        with pytest.raises(CronError) as e:
            check(pattern)
        assert str(e.value) == message


def test_example_schedules_are_valid() -> None:
    for pattern in ["0 6 * * *", "0 8 * * 1", "0 9 1 * *", "0 7 * * 1"]:
        check(pattern)
